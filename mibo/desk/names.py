"""Which program a name means, found the way Start finds one.

The person says 微信, Word or 网易云; the files are Weixin.exe, WINWORD.EXE and cloudmusic.exe. What joins them
is Start's own list (win32.start_apps): each entry's name in this Windows' language and the file it starts. A
name is matched against those names, against what each open window's program says of itself (its file
description, product and file name) and against the window's title. A window already open is taken before a
program is started; a program Start lists and no window shows is the entry to open. No path ever comes from
the model: only what Start lists is started, and only a window's title is read here, never what it shows.

`resolve` is the matching alone, over rows it is given, so it can be measured on a recorded Start menu
(tools/desk_names.py); `find` runs it on this computer.
"""
from __future__ import annotations

import difflib
import os
import re
import time
import unicodedata
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

from . import grants as g, win32

# A score from here on is a match.
FOUND = 0.6
# Two programs this near in score, neither named exactly: the model is asked which one.
CLOSE = 0.03
# The model may give a program's other name after a slash (微信/WeChat).
SEVERAL = re.compile(r"[/|、，,]")
# Start's entry for File Explorer starts no file of its own name; its windows are explorer.exe's.
EXPLORER = "Microsoft.Windows.Explorer"
LISTED = 12


@dataclass(frozen=True)
class App:
    """One entry of Start's list: its name there, what starts it, and the file that runs ("" for an app
    from a package, which is known by its package family instead)."""
    name: str
    aumid: str
    target: str = ""

    @property
    def family(self) -> str:
        return self.aumid.split("!")[0].lower() if "!" in self.aumid else ""

    @property
    def whole(self) -> bool:
        """The program itself, not one use of it: a shortcut with arguments (a prompt of cmd.exe, a notebook
        of python.exe) gets a made-up id from Windows, and other programs' windows are not its own."""
        return not self.aumid.startswith("Microsoft.AutoGenerated.")


@dataclass(frozen=True)
class Window:
    """An open window, with what its program says of itself."""
    hwnd: int
    exe: str
    title: str = ""
    description: str = ""
    product: str = ""

    @property
    def name(self) -> str:
        return self.description or self.product or Path(self.exe).stem


@dataclass
class Found:
    """What a name came to: `hwnd`, an open window; else `app`, an entry of Start to open; else neither, with
    `names` the programs it could have meant (`several`) or the ones with a window open now."""
    hwnd: int = 0
    app: App | None = None
    names: list[str] = field(default_factory=list)
    several: bool = False


def _plain(text: str) -> str:
    return "".join(ch for ch in unicodedata.normalize("NFKC", text).casefold() if ch.isalnum() or ch in "+#")


def _words(text: str) -> set[str]:
    return set(re.findall(r"[a-z0-9]+|[^\W\d_a-z]+", unicodedata.normalize("NFKC", text).casefold()))


def score(asked: str, text: str) -> float:
    """How well the person's word names `text`, 0 to 1: the same name; each word of it (Word for Microsoft
    Word); its beginning (网易云 for 网易云音乐); the name with its maker's in front (腾讯QQ for QQ); a part of
    it (资源管理器 for 文件资源管理器); or a slip of the hand."""
    a, t = _plain(asked), _plain(text)
    if not a or not t:
        return 0.0
    if a == t:
        return 1.0
    part = min(1.0, len(a) / len(t))
    if _words(asked) <= _words(text):
        return 0.8 + 0.15 * part
    if len(a) >= 2 and t.startswith(a):
        return 0.75 + 0.15 * part
    if len(t) >= 2 and a.endswith(t):
        return 0.65 + 0.2 * len(t) / len(a)
    if len(a) >= (3 if a.isascii() else 2) and a in t:
        return 0.6 + 0.15 * part
    return difflib.SequenceMatcher(None, a, t).ratio() - 0.25 if len(a) >= 4 else 0.0


def runs(app: App, exe: str) -> bool:
    """Whether a running file is the program this entry starts: of its package, or the very file."""
    if app.family:
        return win32.package_of(exe).lower() == app.family
    return os.path.normcase(exe) == os.path.normcase(app.target)


def beside(app: App, exe: str) -> bool:
    """Whether a running file lies under the folder of the file this entry starts: a launcher's program
    (钉钉's entry starts DingtalkLauncher.exe, its windows are main\\current\\DingTalk.exe's). Not for a folder
    many programs share (Windows' own)."""
    folder = os.path.normcase(os.path.dirname(app.target))
    system = os.path.normcase(os.environ.get("SystemRoot", r"C:\Windows"))
    return (len(folder) > 3 and not folder.startswith(system)
            and os.path.normcase(exe).startswith(folder + os.sep))


def resolve(asked: str, windows: list[Window], apps: list[App]) -> Found:
    """The window or the Start entry `asked` names. `windows` are the open ones, the front-most first."""
    said = [part for part in SEVERAL.split(asked) if _plain(part)]

    def best(pairs) -> float:
        return max((score(word, text) * weight for word in said for text, weight in pairs if text), default=0.0)

    exact = {w.hwnd for w in windows if any(a.whole and runs(a, w.exe) for a in apps)}
    rows: list[tuple[str, App | None, list[Window]]] = []
    for app in apps:
        mine = [w for w in windows if app.whole and (
            runs(app, w.exe) or (w.hwnd not in exact and beside(app, w.exe)))]
        rows.append((app.name, app, mine))
    joined = {w.hwnd for _, _, mine in rows for w in mine}
    alone: dict[str, list[Window]] = {}
    for w in windows:
        if w.hwnd not in joined:
            alone.setdefault(os.path.normcase(w.exe), []).append(w)
    rows += [(mine[0].name, None, mine) for mine in alone.values()]

    ranked = []
    for order, (name, app, mine) in enumerate(rows):
        stem = Path(app.target).stem if app else ""
        own = best([(name, 1.0), (stem, 0.9)] + [pair for w in mine for pair in (
            (w.description, 1.0), (w.product, 0.8), (Path(w.exe).stem, 0.9))])
        titled = [(best([(w.title, 0.7)]), w) for w in mine]
        value = max([own] + [t for t, _ in titled])
        if value >= FOUND:
            # Among entries of one name (a browser's shortcut to a site, and the program itself), the one
            # whose file is called like it.
            ranked.append((-value, not mine, -score(name, stem), order, name, app,
                           max(titled, key=lambda p: p[0])[1] if titled else None))
    ranked.sort(key=lambda row: row[:4])
    if not ranked:
        open_now = [name for name, app, mine in rows if mine and not g.NEVER_WORDS.search(name)]
        return Found(names=list(dict.fromkeys(open_now))[:LISTED])
    top = ranked[0]
    near = list(dict.fromkeys(row[4] for row in ranked if row[0] - top[0] < CLOSE))
    if -top[0] < 0.95 and len(near) > 1:
        return Found(names=near[:LISTED], several=True)
    return Found(hwnd=top[6].hwnd) if top[6] is not None else Found(app=top[5])


# --- this computer

_facts = lru_cache(maxsize=256)(win32.file_facts)
_apps: tuple[float, list[App]] = (0.0, [])


def apps(fresh: bool = False) -> list[App]:
    """Start's entries that start a program (not the documents, links and help pages listed beside them).
    Read once, about a second's work, and again when a name is not in the list (`find`)."""
    global _apps
    if fresh or not _apps[1]:
        rows = []
        for name, aumid, target in win32.start_apps():
            if aumid == EXPLORER:
                target = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "explorer.exe")
            if "!" in aumid or target.lower().endswith(".exe"):
                rows.append(App(name, aumid, "" if "!" in aumid else target))
        _apps = (time.monotonic(), rows)
    return _apps[1]


def open_windows() -> list[Window]:
    """Each program's main windows on this desktop now (the ones the taskbar lists, so not a splash screen),
    shown or minimised, the front-most first; not the app's own, and not the taskbar, the desktop or a
    terminal (windows never read)."""
    out = []
    for h in win32.top_windows():
        if not win32.on_desktop(h) or win32.owner_of(h) or win32.tool_window(h):
            continue
        pid = g.program_pid(h)
        exe = win32.exe_of(pid)
        if not exe or pid == os.getpid() or g.window_never(Path(exe).name.lower(), h):
            continue
        facts = _facts(exe)
        out.append(Window(h, exe, win32.title_of(h), facts.get("FileDescription", ""), facts.get("ProductName", "")))
    return out


def find(asked: str) -> Found:
    """`resolve` on this computer; Start's list is read again when the name is not in an older one."""
    found = resolve(asked, open_windows(), apps())
    if not (found.hwnd or found.app or found.several) and time.monotonic() - _apps[0] > 10:
        found = resolve(asked, open_windows(), apps(fresh=True))
    return found


def start_name(exe: str) -> str:
    """What Start calls the program a running file belongs to (文件资源管理器 for explorer.exe); "" when Start
    lists none, or more than one."""
    mine = {app.name for app in apps() if app.whole and runs(app, exe)}
    return mine.pop() if len(mine) == 1 else ""
