def fixed() -> int:
    from mibo.desk import names
    apps = [names.App(*row) for row in START]
    windows = [names.Window(i + 1, *row) for i, row in enumerate(OPEN)]
    by_hwnd = {w.hwnd: w for w in windows}
    right = total = 0
    for state, shown in (("open", windows), ("closed", [])):
        for asked, exe, entry in CASES:
            found = names.resolve(asked, shown, apps)
            got = (Path(by_hwnd[found.hwnd].exe).name if found.hwnd else "") if state == "open" and exe else ""
            if state == "open" and exe:
                want, got = f"window of {exe}", f"window of {got}" if got else _said(found)
            else:
                want, got = (f"open {entry}" if entry else "nothing"), _said(found)
                if entry == "Visual Studio Code" and found.app and Path(found.app.target).stem != "Code":
                    got += " (the browser's shortcut)"
            ok = want == got
            right, total = right + ok, total + 1
            print(f"{'ok ' if ok else 'MISS'} {state:6} {asked:20} -> {got}" + ("" if ok else f"   (wanted: {want})"))
    print(f"\n{right} of {total} right")
    return 0 if right == total else 1


def _said(found) -> str:
    if found.hwnd:
        return "a window"
    if found.app:
        return f"open {found.app.name}"
    return ("several: " + ", ".join(found.names)) if found.several else "nothing"


def here(asked: list[str]) -> int:
    from mibo.desk import names
    began = time.perf_counter()
    apps = names.apps()
    read_s = time.perf_counter() - began
    windows = names.open_windows()
    print(f"Start lists {len(apps)} programs here (read in {read_s:.2f} s); {len(windows)} program windows are open; "
          f"Windows names programs in {names.win32.ui_language()}")
    by_hwnd = {w.hwnd: w for w in windows}
    for name in asked:
        began = time.perf_counter()
        found = names.resolve(name, windows, apps)
        took = (time.perf_counter() - began) * 1000
        if found.hwnd:
            w = by_hwnd[found.hwnd]
            said = f"its open window ({names.start_name(w.exe) or w.name}, {Path(w.exe).name})"
        elif found.app:
            said = f"open {found.app.name} ({Path(found.app.target).name or found.app.aumid})"
        else:
            said = ("several: " if found.several else "nothing; open now: ") + ", ".join(found.names)
        print(f"{name:28} -> {said}   [{took:.0f} ms]")
    return 0


def open_one(name: str, home: Path) -> int:
    """Through panel.Desk, as a chat task would: the card, the start from Start's entry, the grant, a look."""
    from types import SimpleNamespace

    from mibo.desk import grants as g, panel, win32
    win32.dpi_aware()
    desktop = home / "runtime" / "desktop"
    g.Grants(desktop).set_on(True)
    desk = panel.Desk(None, SimpleNamespace(home=home, config=lambda: {"PERSONA_NAME": "Mibo"}))
    cards = []

    def answer(card: dict) -> dict:
        cards.append({k: v for k, v in card.items() if k != "picture"})
        return {"answer": "once"} if card.get("type") == "desk_grant" else {"yes": False}
    desk.ask = answer
    before = set(win32.top_windows())
    began = time.monotonic()
    result = desk._begin(f"open {name}", name)
    print(json.dumps({"cards": cards, "result": {k: v for k, v in result.items() if k != "state"},
                      "seconds": round(time.monotonic() - began, 1)}, ensure_ascii=False, indent=1))
    hands = desk.hands
    if hands is not None:
        hwnd = hands.view.hwnd
        second = [m for m in win32.monitors() if not m["primary"]]
        if second and hwnd not in before:
            win32.place(hwnd, second[0]["left"] + 80, second[0]["top"] + 80)
        look = hands.look()
        print("\n".join(str(look.get("state") or look.get("line") or "").splitlines()[:8]))
        hands.end("done", "")
        if hwnd not in before:
            # Only the window this run opened is closed.
            win32.close(hwnd)
    return 0 if result.get("status") == "ok" else 1


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--here", nargs="+", metavar="NAME")
    parser.add_argument("--open", metavar="NAME")
    parser.add_argument("--home", default=os.environ.get("AGENT_HOME", ""))
    args = parser.parse_args()
    if args.open:
        if not args.home:
            parser.error("--open needs --home DIR")
        return open_one(args.open, Path(args.home))
    return here(args.here) if args.here else fixed()


if __name__ == "__main__":
    raise SystemExit(main())
